#!/usr/bin/env node
// Generates src/routes/validators.generated.ts: the request-body validators as ajv STANDALONE code, compiled once at build
// time from the schemas in src/routes/schema-defs.ts (RP5). Both hosts (the Worker build and the Lambda bundle) import that
// one file, so nothing compiles a schema at module load (84% of the bundle's 68-88 ms import on the Mac) and ajv is not a
// run-time import.
//
//   node scripts/build-validators.mjs            write the file
//   node scripts/build-validators.mjs --check    exit 1 if the file on disk is not what the schemas generate
//
// tests/platform/validators.test.ts imports `generate()` and fails when the committed file is stale, and compares the
// generated validators with ajv's run-time compile of the same schemas on a corpus.
import fs from "node:fs";
import path from "node:path";
import url from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";
import { SCHEMAS } from "../src/routes/schema-defs.ts";

const ROOT = path.join(path.dirname(url.fileURLToPath(import.meta.url)), "..");
export const OUT = path.join(ROOT, "src", "routes", "validators.generated.ts");

const pick = (m) => (typeof m === "function" ? m : m.default);
const Ajv = pick(Ajv2020);
const standaloneCode = pick(standalone);

/** Same options the run-time compile used before RP5: strict, first error only. */
export const AJV_OPTIONS = { allErrors: false, strict: true };

// ajv's standalone output `require`s its tiny runtime helpers even in ESM mode. A bundler would resolve that, a plain ESM
// loader would not, and CJS interop differs between them; so each helper this repo's schemas need is inlined here, and any
// other `require(` is an error that says what to add.
const INLINE = {
  "ajv/dist/runtime/ucs2length": () => {
    const src = fs.readFileSync(path.join(ROOT, "node_modules", "ajv", "dist", "runtime", "ucs2length.js"), "utf8");
    const fn = /function ucs2length\(str\) \{[\s\S]*?\n\}/.exec(src);
    if (fn === null) throw new Error("build-validators: cannot find ucs2length in ajv/dist/runtime/ucs2length.js");
    return { name: "ucs2length", code: fn[0] };
  },
};

export function generate() {
  const ajv = new Ajv({ ...AJV_OPTIONS, code: { source: true, esm: true } });
  for (const [name, schema] of Object.entries(SCHEMAS)) ajv.addSchema(schema, name);
  let code = standaloneCode(ajv).replace(/^"use strict";/, "");
  const helpers = new Map();
  code = code.replace(/require\("([^"]+)"\)\.default/g, (whole, mod) => {
    const inline = INLINE[mod];
    if (inline === undefined) throw new Error(`build-validators: the generated code needs ${whole}; inline it in scripts/build-validators.mjs INLINE`);
    const h = inline();
    helpers.set(mod, h);
    return h.name;
  });
  if (/\brequire\(/.test(code)) throw new Error("build-validators: the generated code still calls require()");
  code = code.replace(/;export const /g, ";\nexport const ");
  const version = JSON.parse(fs.readFileSync(path.join(ROOT, "node_modules", "ajv", "package.json"), "utf8")).version;
  const banner =
    `// GENERATED by scripts/build-validators.mjs from src/routes/schema-defs.ts (ajv ${version} standalone). Do not edit:\n` +
    `// run \`npm run build:validators\`. tests/platform/validators.test.ts fails when this file is stale (RP5).\n` +
    `// @ts-nocheck\n`;
  return banner + [...helpers.values()].map((h) => h.code).join("\n") + (helpers.size > 0 ? "\n" : "") + code + "\n";
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === url.fileURLToPath(import.meta.url)) {
  const next = generate();
  if (process.argv.includes("--check")) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (have !== next) {
      console.error(`${path.relative(ROOT, OUT)} is stale: run npm run build:validators`);
      process.exit(1);
    }
    console.log("validators are up to date");
  } else {
    fs.writeFileSync(OUT, next);
    console.log(`wrote ${path.relative(ROOT, OUT)} (${next.length} bytes, ${Object.keys(SCHEMAS).length} validators)`);
  }
}
