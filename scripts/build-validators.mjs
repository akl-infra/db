#!/usr/bin/env node
// Generates every precompiled validator module as ajv STANDALONE code, compiled once at build time (RP5):
//
//   src/routes/validators.generated.ts           the 19 request-body schemas of src/routes/schema-defs.ts
//   formats/spark/1/validate.generated.ts        spark/1's payload schema (discriminator hint, allErrors: false)
//   formats/spark/1/validate-all.generated.ts    the same schema with allErrors: true (the error-picking pass)
//   formats/mana2/1/validate.generated.ts        mana2/1's payload schema
//   formats/adapters/cmini/validate.generated.ts the cmini adapter's payload schema
//
// All of them are imported by both hosts (the Worker build and the Lambda bundle), so nothing compiles a schema at module
// load (84% of the bundle's 68-88 ms import on the Mac) and ajv is not a run-time import anywhere.
//
//   node scripts/build-validators.mjs            write the files
//   node scripts/build-validators.mjs --check    exit 1 if any file on disk is not what the schemas generate
//
// tests/platform/validators.test.ts and tests/formats/validators-equivalence.test.ts import `TARGETS`, fail when a committed
// file is stale, and compare each generated validator with ajv's run-time compile of the same schema on a corpus.
import fs from "node:fs";
import path from "node:path";
import url from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";
import { SCHEMAS } from "../src/routes/schema-defs.ts";
import { validationSchema as sparkValidationSchema } from "../formats/spark/1/validation-schema.ts";

const ROOT = path.join(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const pick = (m) => (typeof m === "function" ? m : m.default);
const Ajv = pick(Ajv2020);
const standaloneCode = pick(standalone);
const readJson = (rel) => JSON.parse(fs.readFileSync(path.join(ROOT, rel), "utf8"));

/** Same options the run-time compiles used before RP5: strict, first error only. */
export const AJV_OPTIONS = { allErrors: false, strict: true };

// ajv's standalone output `require`s its tiny runtime helpers even in ESM mode. A bundler would resolve that, a plain ESM
// loader would not, and CJS interop differs between them; so each helper this repo's schemas need is inlined here, and any
// other `require(` is an error that says what to add.
const INLINE = {
  "ajv/dist/runtime/ucs2length": () => {
    const src = fs.readFileSync(path.join(ROOT, "node_modules", "ajv", "dist", "runtime", "ucs2length.js"), "utf8");
    const fn = /function ucs2length\(str\) \{[\s\S]*?\n\}/.exec(src);
    if (fn === null) throw new Error("build-validators: cannot find ucs2length in ajv/dist/runtime/ucs2length.js");
    return { name: "ucs2length", code: fn[0] };
  },
};

/** One standalone module for `schemas` (name -> schema; each name becomes an export). */
export function generateModule({ banner, schemas, options }) {
  const ajv = new Ajv({ ...options, code: { source: true, esm: true } });
  for (const [name, schema] of Object.entries(schemas)) ajv.addSchema(schema, name);
  let code = standaloneCode(ajv).replace(/^"use strict";/, "");
  const helpers = new Map();
  code = code.replace(/require\("([^"]+)"\)\.default/g, (whole, mod) => {
    const inline = INLINE[mod];
    if (inline === undefined) throw new Error(`build-validators: the generated code needs ${whole}; inline it in scripts/build-validators.mjs INLINE`);
    const h = inline();
    helpers.set(mod, h);
    return h.name;
  });
  if (/\brequire\(/.test(code)) throw new Error("build-validators: the generated code still calls require()");
  code = code.replace(/;export const /g, ";\nexport const ");
  const version = JSON.parse(fs.readFileSync(path.join(ROOT, "node_modules", "ajv", "package.json"), "utf8")).version;
  const head =
    `// GENERATED by scripts/build-validators.mjs from ${banner} (ajv ${version} standalone). Do not edit:\n` +
    `// run \`npm run build:validators\` in db/. A test fails when this file is stale (RP5).\n` +
    `// @ts-nocheck\n`;
  return head + [...helpers.values()].map((h) => h.code).join("\n") + (helpers.size > 0 ? "\n" : "") + code + "\n";
}

/** Every generated file: where it goes, the schemas and options it is generated from, and a function that builds its text. */
export const TARGETS = [
  { out: "src/routes/validators.generated.ts", banner: "src/routes/schema-defs.ts", schemas: () => SCHEMAS, options: AJV_OPTIONS },
  { out: "formats/spark/1/validate.generated.ts", banner: "formats/spark/1/validation-schema.ts", schemas: () => ({ validate: sparkValidationSchema }), options: { allErrors: false, strict: true, discriminator: true } },
  { out: "formats/spark/1/validate-all.generated.ts", banner: "formats/spark/1/validation-schema.ts (allErrors: true)", schemas: () => ({ validate: sparkValidationSchema }), options: { allErrors: true, strict: true, discriminator: true } },
  { out: "formats/mana2/1/validate.generated.ts", banner: "formats/mana2/1/schema.json", schemas: () => ({ validate: readJson("formats/mana2/1/schema.json") }), options: AJV_OPTIONS },
  { out: "formats/adapters/cmini/validate.generated.ts", banner: "formats/adapters/cmini/schema.json", schemas: () => ({ validate: readJson("formats/adapters/cmini/schema.json") }), options: AJV_OPTIONS },
].map((t) => ({ ...t, path: path.join(ROOT, t.out), generate: () => generateModule({ banner: t.banner, schemas: t.schemas(), options: t.options }) }));

/** The route-body validators' text (kept for tests/platform/validators.test.ts). */
export const OUT = TARGETS[0].path;
export const generate = () => TARGETS[0].generate();

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === url.fileURLToPath(import.meta.url)) {
  let stale = 0;
  for (const t of TARGETS) {
    const next = t.generate();
    if (process.argv.includes("--check")) {
      const have = fs.existsSync(t.path) ? fs.readFileSync(t.path, "utf8") : "";
      if (have !== next) {
        console.error(`${t.out} is stale: run npm run build:validators`);
        stale++;
      }
    } else {
      fs.writeFileSync(t.path, next);
      console.log(`wrote ${t.out} (${next.length} bytes)`);
    }
  }
  if (process.argv.includes("--check")) {
    if (stale > 0) process.exit(1);
    console.log("validators are up to date");
  }
}
