// Lane J's slice of the item model (src/store/ddb/contracts.ts `LaneSchema`,
// design/p2-p5-briefs.md): rows of these tables <-> their DynamoDB items.
//
//   link_submissions            SUB#link#<id>/ROW        + IX#link#st#.., IX#link#lay#..    + guard L#<layout>/SET#link
//   wpm_submissions             SUB#wpm#<id>/ROW         + IX#wpm#st#.., #pair#.., IX#wpm#ok + guard L#<layout>/SET#wpm#<user>
//   layout_comments             SUB#comment#<id>/ROW     + IX#cmt#st#.., #pair#.., #ok#.., #user#.. + CC/<layout> + guard L#<layout>/SET#cmt#<user>
//   comment_likes               CL#<layout>/<author>#<user> + CLA#<author>/<layout>#<user> + guard L#<layout>/SET#cl#<author>
//   moderation_review_history   SUB#<kind>#<id>/H#<n>    + SUB#<kind>#<id>/HK#<rv>#<action> (claim)
//
// The rows are D1-shaped; `fromItems` reads only the primary items. Derived
// items are regenerated by `toItems`, which is also what the index checker
// compares the live ones against. `META/REVIEW_HISTORY.last` is D1's AUTOINCREMENT as a counter (the highest history id; import sets it to the max id, and incremental inserts must keep the max). COUNTERS: `CC/<layout>.count` and every
// `SET#...` guard `.ver` are sums over several rows, so a harness that inserts
// rows incrementally must `ADD` them (`counterAttribute` names which), never
// overwrite them from a partial batch.
import type { D1Row, Item, LaneSchema, RowsByTable } from "../contracts";
import {
  commentCountKey,
  commentGuardKey,
  commentLikeByAuthorKey,
  commentLikeGuardKey,
  commentLikeKey,
  historyClaimKey,
  historyKey,
  linkGuardKey,
  wpmGuardKey,
  type SubmissionKind,
} from "../keys-community";
import { indexItems, REVIEW_HISTORY_COUNTER, isLiveComment, itemRow, normalizeRow, pick, rowItem } from "../community";

const LIKE_COLUMNS = ["layout_id", "author_id", "user_id", "via", "created_at"] as const;
const HISTORY_COLUMNS = ["id", "kind", "submission_id", "action", "actor", "at", "reason", "review_version"] as const;

/** The counter attribute of a derived item, or null for an item that is not a counter. */
export function counterAttribute(item: Item): "count" | "ver" | "last" | null {
  const pk = item.pk as string;
  const sk = item.sk as string;
  if (pk === "CC") return "count";
  if (pk === "META" && sk === "REVIEW_HISTORY") return "last";
  if (pk.startsWith("L#") && sk.startsWith("SET#")) return "ver";
  return null;
}

function count(map: Map<string, number>, key: string, by = 1): void {
  map.set(key, (map.get(key) ?? 0) + by);
}

function toItems(rows: RowsByTable): { main: Item[]; ephemeral: Item[] } {
  const main: Item[] = [];

  const linkVer = new Map<string, number>();
  for (const r of rows.link_submissions ?? []) {
    const row = normalizeRow("link", r);
    main.push({ ...rowItem("link", row) }, ...indexItems("link", row));
    count(linkVer, row.layout_id as string);
  }
  for (const [layout, ver] of linkVer) main.push({ ...linkGuardKey(layout), ver });

  const wpmVer = new Map<string, number>();
  for (const r of rows.wpm_submissions ?? []) {
    const row = normalizeRow("wpm", r);
    main.push(rowItem("wpm", row), ...indexItems("wpm", row));
    count(wpmVer, `${row.layout_id}\u0000${row.user_id}`, 1 + (row.review_version as number));
  }
  for (const [k, ver] of wpmVer) {
    const [layout, user] = k.split("\u0000") as [string, string];
    main.push({ ...wpmGuardKey(layout, user), ver });
  }

  const cmtVer = new Map<string, number>();
  const cmtCount = new Map<string, number>();
  for (const r of rows.layout_comments ?? []) {
    const row = normalizeRow("comment", r);
    main.push(rowItem("comment", row), ...indexItems("comment", row));
    count(cmtVer, `${row.layout_id}\u0000${row.user_id}`, 1 + (row.review_version as number));
    count(cmtCount, row.layout_id as string, isLiveComment(row) ? 1 : 0);
  }
  for (const [k, ver] of cmtVer) {
    const [layout, user] = k.split("\u0000") as [string, string];
    main.push({ ...commentGuardKey(layout, user), ver });
  }
  for (const [layout, n] of cmtCount) main.push({ ...commentCountKey(layout), count: n });

  const likeVer = new Map<string, number>();
  for (const r of rows.comment_likes ?? []) {
    const like = pick(r, LIKE_COLUMNS);
    const layout = like.layout_id as string;
    const author = like.author_id as string;
    const user = like.user_id as string;
    main.push({ ...commentLikeKey(layout, author, user), ...like }, { ...commentLikeByAuthorKey(author, layout, user), ...like });
    count(likeVer, `${layout}\u0000${author}`);
  }
  for (const [k, ver] of likeVer) {
    const [layout, author] = k.split("\u0000") as [string, string];
    main.push({ ...commentLikeGuardKey(layout, author), ver });
  }

  // History: the per-submission ordinal replaces the global AUTOINCREMENT, in id order.
  const bySubmission = new Map<string, D1Row[]>();
  for (const h of rows.moderation_review_history ?? []) {
    const k = `${h.kind}\u0000${h.submission_id}`;
    const list = bySubmission.get(k) ?? [];
    list.push(h);
    bySubmission.set(k, list);
  }
  for (const list of bySubmission.values()) {
    list.sort((a, b) => (a.id as number) - (b.id as number));
    const claims = new Set<string>();
    list.forEach((h, i) => {
      const n = i + 1;
      const kind = h.kind as "comment" | "wpm";
      const claim = `${h.review_version}#${h.action}`;
      if (claims.has(claim)) throw new Error(`moderation_review_history: duplicate (${kind}, ${h.submission_id}, ${claim})`);
      claims.add(claim);
      const body = pick(h, HISTORY_COLUMNS);
      main.push(
        { ...historyKey(kind, h.submission_id as string, n), ...body, n },
        { ...historyClaimKey(kind, h.submission_id as string, h.review_version as number, h.action as string), n, kind, submission_id: h.submission_id, action: h.action, actor: h.actor, review_version: h.review_version },
      );
    });
  }

  const ids = (rows.moderation_review_history ?? []).map((h) => h.id as number);
  if (ids.length > 0) main.push({ ...REVIEW_HISTORY_COUNTER, last: Math.max(...ids) });

  return { main, ephemeral: [] };
}

function tableOf(item: Item): ReturnType<LaneSchema["tableOf"]> {
  const pk = item.pk as string;
  const sk = item.sk as string;
  if (pk === "META" && sk === "REVIEW_HISTORY") return "moderation_review_history";
  if (pk.startsWith("SUB#")) {
    if (sk === "ROW") return pk.startsWith("SUB#link#") ? "link_submissions" : pk.startsWith("SUB#wpm#") ? "wpm_submissions" : pk.startsWith("SUB#comment#") ? "layout_comments" : null;
    if (sk.startsWith("H#") || sk.startsWith("HK#")) return "moderation_review_history";
    return null;
  }
  if (pk.startsWith("IX#link#")) return "link_submissions";
  if (pk.startsWith("IX#wpm#")) return "wpm_submissions";
  if (pk.startsWith("IX#cmt#") || pk === "CC") return "layout_comments";
  if (pk.startsWith("CL#") || pk.startsWith("CLA#")) return "comment_likes";
  if (pk.startsWith("L#")) {
    if (sk === "SET#link") return "link_submissions";
    if (sk.startsWith("SET#wpm#")) return "wpm_submissions";
    if (sk.startsWith("SET#cmt#")) return "layout_comments";
    if (sk.startsWith("SET#cl#")) return "comment_likes";
  }
  return null;
}

const bytes = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

export const communitySchema: LaneSchema = {
  lane: "J",
  tables: ["link_submissions", "wpm_submissions", "layout_comments", "comment_likes", "moderation_review_history"],
  toItems: (rows) => toItems(rows),
  tableOf,
  fromItems({ main }) {
    const out: RowsByTable = { link_submissions: [], wpm_submissions: [], layout_comments: [], comment_likes: [], moderation_review_history: [] };
    const tables: Record<SubmissionKind, D1Row[]> = { link: out.link_submissions!, wpm: out.wpm_submissions!, comment: out.layout_comments! };
    for (const it of main) {
      const pk = it.pk as string;
      const sk = it.sk as string;
      if (pk.startsWith("SUB#") && sk === "ROW") {
        const kind = pk.split("#")[1] as SubmissionKind;
        tables[kind]?.push(itemRow(kind, it));
      } else if (pk.startsWith("SUB#") && sk.startsWith("H#")) {
        out.moderation_review_history!.push(pick(it, HISTORY_COLUMNS));
      } else if (pk.startsWith("CL#")) {
        out.comment_likes!.push(pick(it, LIKE_COLUMNS));
      }
    }
    for (const t of [out.link_submissions!, out.wpm_submissions!, out.layout_comments!]) t.sort((a, b) => bytes(a.id as string, b.id as string));
    out.comment_likes!.sort(
      (a, b) => bytes(a.layout_id as string, b.layout_id as string) || bytes(a.author_id as string, b.author_id as string) || bytes(a.user_id as string, b.user_id as string),
    );
    out.moderation_review_history!.sort((a, b) => (a.id as number) - (b.id as number));
    return out;
  },
};
